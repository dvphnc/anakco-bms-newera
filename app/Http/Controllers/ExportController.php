            'Teens (13-17)' => Resident::whereBetween(\DB::raw('TIMESTAMPDIFF(YEAR, birthdate, CURDATE())'), [13, 17])->count(),
            'Adults (18-59)' => Resident::whereBetween(\DB::raw('TIMESTAMPDIFF(YEAR, birthdate, CURDATE())'), [18, 59])->count(),
            'Seniors (60+)' => Resident::where(\DB::raw('TIMESTAMPDIFF(YEAR, birthdate, CURDATE())'), '>=', 60)->count(),
        ];

        $residentsByPurok = Purok::withCount(['residents' => fn ($q) => $q->where('residency_status', 'Active')])
            ->orderBy('name')->get();

        if ($format === 'pdf') {
            return Pdf::loadView('exports.pdf.analytics', compact(
                'generatedAt', 'generatedBy', 'officialName', 'secretaryName',
                'totalResidents', 'totalActive', 'totalDeceased', 'totalTransferred',
                'totalMale', 'totalFemale', 'totalHouseholds',
                'totalVoters', 'totalSeniors', 'totalPwd', 'totalSoloParent', 'total4ps',
                'ageGroups', 'residentsByPurok'
            ))->setPaper('a4', 'portrait')->stream("population-summary-{$date}.pdf");
        }

        // Excel
        $ss = new Spreadsheet;
        $sheet = $ss->getActiveSheet()->setTitle('Population Summary');

        // Title row
        $sheet->setCellValue('A1', 'BARANGAY NEW ERA — POPULATION SUMMARY REPORT');
        $sheet->setCellValue('A2', 'As of '.now()->format('F d, Y'));
        $sheet->setCellValue('A3', 'Generated by: '.$generatedBy.' | '.$generatedAt);
        $sheet->getStyle('A1')->applyFromArray(['font' => ['bold' => true, 'size' => 14, 'color' => ['argb' => 'FF0D2144']]]);
        $sheet->getStyle('A2:A3')->applyFromArray(['font' => ['size' => 9, 'color' => ['argb' => 'FF666666']]]);

        // Overall Population
        $sheet->setCellValue('A5', 'OVERALL POPULATION');
        $sheet->getStyle('A5')->applyFromArray(['font' => ['bold' => true, 'color' => ['argb' => 'FFFFFFFF']], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FF0D2144']]]);
        $sheet->mergeCells('A5:B5');

        $popData = [['Total Residents', $totalResidents], ['Active', $totalActive], ['Deceased', $totalDeceased], ['Transferred', $totalTransferred], ['Total Households', $totalHouseholds]];
        $row = 6;
        foreach ($popData as $i => $d) {
            $sheet->setCellValue("A{$row}", $d[0]);
            $sheet->setCellValue("B{$row}", $d[1]);
            $bg = $row % 2 === 0 ? 'FFF5F7FA' : 'FFFFFFFF';
            $sheet->getStyle("A{$row}:B{$row}")->applyFromArray(['fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => $bg]]]);
            $row++;
        }

        // Gender
        $row++;
        $sheet->setCellValue("A{$row}", 'GENDER DISTRIBUTION');
        $sheet->getStyle("A{$row}")->applyFromArray(['font' => ['bold' => true, 'color' => ['argb' => 'FFFFFFFF']], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FF0D2144']]]);
        $sheet->mergeCells("A{$row}:C{$row}");
        $row++;
        $sheet->fromArray(['Gender', 'Count', '%'], null, "A{$row}");
        $sheet->getStyle("A{$row}:C{$row}")->applyFromArray(['font' => ['bold' => true], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FFE8EDF5']]]);
        $row++;
        $total = $totalMale + $totalFemale;
        $sheet->fromArray(['Male', $totalMale, $total > 0 ? round(($totalMale / $total) * 100).'%' : '0%'], null, "A{$row}");
        $row++;
        $sheet->fromArray(['Female', $totalFemale, $total > 0 ? round(($totalFemale / $total) * 100).'%' : '0%'], null, "A{$row}");
        $row++;

        // Age Groups
        $row++;
        $sheet->setCellValue("A{$row}", 'AGE GROUPS');
        $sheet->getStyle("A{$row}")->applyFromArray(['font' => ['bold' => true, 'color' => ['argb' => 'FFFFFFFF']], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FF0D2144']]]);
        $sheet->mergeCells("A{$row}:C{$row}");
        $row++;
        $sheet->fromArray(['Age Group', 'Count', '%'], null, "A{$row}");
        $sheet->getStyle("A{$row}:C{$row}")->applyFromArray(['font' => ['bold' => true], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FFE8EDF5']]]);
        $row++;
        foreach ($ageGroups as $label => $count) {
            $pct = $totalActive > 0 ? round(($count / $totalActive) * 100).'%' : '0%';
            $sheet->fromArray([$label, $count, $pct], null, "A{$row}");
            $row++;
        }

        // Special Classifications
        $row++;
        $sheet->setCellValue("A{$row}", 'SPECIAL CLASSIFICATIONS');
        $sheet->getStyle("A{$row}")->applyFromArray(['font' => ['bold' => true, 'color' => ['argb' => 'FFFFFFFF']], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FF0D2144']]]);
        $sheet->mergeCells("A{$row}:C{$row}");
        $row++;
        $sheet->fromArray(['Classification', 'Count', '% of Active'], null, "A{$row}");
        $sheet->getStyle("A{$row}:C{$row}")->applyFromArray(['font' => ['bold' => true], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FFE8EDF5']]]);
        $row++;
        $classifications = [['Registered Voters', $totalVoters], ['Senior Citizens', $totalSeniors], ['PWD', $totalPwd], ['Solo Parents', $totalSoloParent], ['4Ps Beneficiaries', $total4ps]];
        foreach ($classifications as $c) {
            $pct = $totalActive > 0 ? round(($c[1] / $totalActive) * 100).'%' : '0%';
            $sheet->fromArray([$c[0], $c[1], $pct], null, "A{$row}");
            $row++;
        }

        // Residents by Purok
        $row++;
        $sheet->setCellValue("A{$row}", 'RESIDENTS BY PUROK');
        $sheet->getStyle("A{$row}")->applyFromArray(['font' => ['bold' => true, 'color' => ['argb' => 'FFFFFFFF']], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FF0D2144']]]);
        $sheet->mergeCells("A{$row}:C{$row}");
        $row++;
        $sheet->fromArray(['Purok', 'Residents', '% of Total'], null, "A{$row}");
        $sheet->getStyle("A{$row}:C{$row}")->applyFromArray(['font' => ['bold' => true], 'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FFE8EDF5']]]);
        $row++;
        foreach ($residentsByPurok as $purok) {
            $pct = $totalActive > 0 ? round(($purok->residents_count / $totalActive) * 100).'%' : '0%';
            $sheet->fromArray([$purok->name, $purok->residents_count, $pct], null, "A{$row}");
            $row++;
        }

        // Column widths
        $sheet->getColumnDimension('A')->setWidth(30);
        $sheet->getColumnDimension('B')->setWidth(15);
        $sheet->getColumnDimension('C')->setWidth(15);

        $this->addMetaSheet($ss, 'Analytics', $totalResidents, $generatedBy);

        return $this->streamXlsx($ss, "population-summary-{$date}.xlsx");
    }
