    // -------------------------------------------------------
    // SHARED — Apply navy header style to a sheet
    // -------------------------------------------------------
    private function styleSheet($sheet, array $headers, array $colWidths): void
    {
        $colCount = count($headers);
        $lastCol = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex($colCount);

        // Write headers
        foreach ($headers as $i => $h) {
            $col = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex($i + 1);
            $sheet->setCellValue($col.'1', $h);
        }

        // Header row style — navy bg, white bold text
        $sheet->getStyle("A1:{$lastCol}1")->applyFromArray([
            'font' => [
                'bold' => true,
                'color' => ['argb' => 'FFFFFFFF'],
                'size' => 10,
            ],
            'fill' => [
                'fillType' => Fill::FILL_SOLID,
                'startColor' => ['argb' => 'FF0D2144'],
            ],
            'alignment' => [
                'horizontal' => Alignment::HORIZONTAL_CENTER,
                'vertical' => Alignment::VERTICAL_CENTER,
            ],
        ]);
        $sheet->getRowDimension(1)->setRowHeight(20);

        // Column widths
        foreach ($colWidths as $col => $width) {
            $sheet->getColumnDimension($col)->setWidth($width);
        }
    }

    private function styleDataRows($sheet, int $rowCount, int $colCount): void
    {
        $lastCol = \PhpOffice\PhpSpreadsheet\Cell\Coordinate::stringFromColumnIndex($colCount);

        for ($row = 2; $row <= $rowCount + 1; $row++) {
            // Alternating rows
            $bg = $row % 2 === 0 ? 'FFF5F7FA' : 'FFFFFFFF';
            $sheet->getStyle("A{$row}:{$lastCol}{$row}")->applyFromArray([
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => $bg]],
                'alignment' => ['vertical' => Alignment::VERTICAL_CENTER],
            ]);
            $sheet->getRowDimension($row)->setRowHeight(16);
        }

        // Border around all data
        $sheet->getStyle("A1:{$lastCol}".($rowCount + 1))->applyFromArray([
            'borders' => [
                'allBorders' => [
                    'borderStyle' => Border::BORDER_THIN,
                    'color' => ['argb' => 'FFE5E7EB'],
                ],
            ],
        ]);

        // Freeze header row
        $sheet->freezePane('A2');
    }

    private function addMetaSheet($spreadsheet, string $module, int $count, string $generatedBy, string $filtersApplied = 'None (all records)'): void
    {
        $meta = $spreadsheet->createSheet();
        $meta->setTitle('Info');
        $meta->setCellValue('A1', 'Barangay New Era BMS — Export Info');
        $meta->setCellValue('A2', 'Module');
        $meta->setCellValue('B2', ucfirst($module));
        $meta->setCellValue('A3', 'Total Records');
        $meta->setCellValue('B3', $count);
        $meta->setCellValue('A4', 'Filters Applied');
        $meta->setCellValue('B4', $filtersApplied);
        $meta->setCellValue('A5', 'Generated By');
        $meta->setCellValue('B5', $generatedBy);
        $meta->setCellValue('A6', 'Generated At');
        $meta->setCellValue('B6', now()->format('F d, Y h:i A'));
        $meta->setCellValue('A7', 'Barangay');
        $meta->setCellValue('B7', 'Barangay New Era, Quezon City');

        $meta->getStyle('A1')->applyFromArray([
            'font' => ['bold' => true, 'size' => 12, 'color' => ['argb' => 'FF0D2144']],
        ]);
        $meta->getStyle('A2:A7')->applyFromArray([
            'font' => ['bold' => true],
        ]);
        // Highlight filters row if filters are active
        if ($filtersApplied !== 'None (all records)') {
            $meta->getStyle('A4:B4')->applyFromArray([
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['argb' => 'FFFFF3CD']],
